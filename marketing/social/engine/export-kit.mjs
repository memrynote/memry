#!/usr/bin/env node
/**
 * The posting checklist and kit, from 2026-q4.md and the approved media in media/.
 *
 *   node marketing/social/engine/export-kit.mjs
 *
 * - CHECKLIST.md (tracked): every post day, checked when all its media is approved; each post's
 *   media is "hazır" (approved, in media/) or "bekliyor" (not made or not checked yet).
 * - kit/<date>/ (gitignored): that day's approved media, plus the GIF when the clip's local render
 *   has one, and a post.md with the X post, its first reply and the r/MemryNote post.
 * Media gets into media/ only through engine/approve.mjs, after its QA stills were looked at.
 */
import * as fs from 'node:fs'
import * as path from 'node:path'
import { fileURLToPath } from 'node:url'

const SOCIAL = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const KIT = path.join(SOCIAL, 'kit')
const MEDIA = path.join(SOCIAL, 'media')
const DEFAULT_REPLY = 'memrynote.com: free on mac, windows and linux'
const MONTHS = { Oct: '10', Nov: '11', Dec: '12', Jan: '01' }

const lines = fs.readFileSync(path.join(SOCIAL, '2026-q4.md'), 'utf8').split('\n')
const quote = (i) => {
  while (lines[i] === '') i++
  const q = []
  while (lines[i]?.startsWith('>')) q.push(lines[i++].replace(/^> ?/, ''))
  return q.join('\n').trim()
}
const days = []
let day = null
let week = null
for (let i = 0; i < lines.length; i++) {
  const l = lines[i]
  if (l.startsWith('## ')) {
    day = null
    week = /^## Week \d+:/.test(l)
      ? l.slice(3)
      : l === '## Floating posts'
        ? 'Floating posts'
        : null
    continue
  }
  const h = l.match(/^### (\w{3}) (Oct|Nov|Dec|Jan) (\d+) · (.+)$/)
  const f = l.match(/^### (F\d+) · (.+)$/)
  if (week && (h || f)) {
    day = h
      ? {
          week,
          date: `${h[2] === 'Jan' ? 2027 : 2026}-${MONTHS[h[2]]}-${h[3].padStart(2, '0')}`,
          label: `${h[1]} ${h[2]} ${h[3]}`,
          title: h[4]
        }
      : { week, date: `floating-${f[1]}`, label: f[1], title: f[2] }
    days.push(day)
    continue
  }
  if (!day) continue
  const x = l.match(/^\*\*X\*\* · (?:(.+?) · )?(?:🎬|🖼️|🧩) `([a-z0-9-]+)`/)
  if (x)
    day.x = { when: x[1] ?? 'on the day', slug: x[2], text: quote(i + 1), reply: DEFAULT_REPLY }
  const reply = l.match(/^↳ first reply: `(.+)`/)
  if (reply && day.x) day.x.reply = reply[1]
  const r = l.match(
    /^\*\*r\/MemryNote\*\* · `\[(.+?)\]` \*\*(.+?)\*\*(?: · (?:🎬|🖼️|🧩) `([a-z0-9-]+)`)?/
  )
  // A Reddit post reuses the day's X clip unless it names its own (the Saturday roundups).
  if (r) day.reddit = { flair: r[1], title: r[2], slug: r[3] ?? day.x?.slug, body: quote(i + 1) }
}
const posts = days.filter((d) => d.x)
const ready = (slug) => fs.existsSync(path.join(MEDIA, `${slug}.mp4`))

// ------------------------------------------------------------------ checklist
const status = (slug) => `\`${slug}\` ${ready(slug) ? 'hazır' : '**bekliyor**'}`
const dated = posts.filter((d) => !d.date.startsWith('floating'))
const xReady = dated.filter((d) => ready(d.x.slug)).length
const reddit = dated.filter((d) => d.reddit)
const rReady = reddit.filter((d) => ready(d.reddit.slug)).length
const out = [
  '# Posting checklist',
  '',
  'Generated by `node marketing/social/engine/export-kit.mjs` from [2026-q4.md](2026-q4.md) and the',
  "approved media in [media/](media/). Don't edit by hand. A day is checked when all its media is",
  'approved. **hazır**: approved, in `media/`. **bekliyor**: not made or not checked yet.',
  '',
  `X: ${xReady}/${dated.length} hazır · r/MemryNote: ${rReady}/${reddit.length} hazır`
]
let current = null
for (const d of posts) {
  if (d.week !== current) out.push('', `## ${(current = d.week)}`, '')
  const all = ready(d.x.slug) && (!d.reddit || ready(d.reddit.slug))
  const parts = [`X ${status(d.x.slug)}`]
  if (d.reddit) parts.push(`Reddit ${status(d.reddit.slug)}`)
  out.push(`- [${all ? 'x' : ' '}] **${d.label}** · ${d.title} · ${parts.join(' · ')}`)
}
fs.writeFileSync(path.join(SOCIAL, 'CHECKLIST.md'), out.join('\n') + '\n')

// ------------------------------------------------------------------ kit
fs.rmSync(KIT, { recursive: true, force: true })
function copyMedia(slug, dest) {
  if (!ready(slug)) return null
  const files = [
    path.join(MEDIA, `${slug}.mp4`),
    path.join(MEDIA, `${slug}.png`),
    path.join(SOCIAL, 'clips', slug, 'out', `${slug}.gif`)
  ]
  for (const f of files.filter((x) => fs.existsSync(x)))
    fs.copyFileSync(f, path.join(dest, path.basename(f)))
  return `${slug}.mp4`
}
for (const d of posts) {
  const dest = path.join(KIT, d.date)
  fs.mkdirSync(dest, { recursive: true })
  const xMedia = copyMedia(d.x.slug, dest)
  const rMedia = d.reddit && (d.reddit.slug === d.x.slug ? xMedia : copyMedia(d.reddit.slug, dest))
  const md = [
    `# ${d.label} · ${d.title}`,
    '',
    `## X · ${d.x.when}`,
    '',
    `Media: ${xMedia ?? `bekliyor (${d.x.slug})`}`,
    '',
    '```text',
    d.x.text,
    '```',
    '',
    'First reply:',
    '',
    '```text',
    d.x.reply,
    '```'
  ]
  if (d.reddit)
    md.push(
      '',
      `## r/MemryNote · ~10:00 AM ET · [${d.reddit.flair}]`,
      '',
      `Media: ${rMedia ?? `bekliyor (${d.reddit.slug})`}`,
      '',
      `**${d.reddit.title}**`,
      '',
      d.reddit.body
    )
  fs.writeFileSync(path.join(dest, 'post.md'), md.join('\n') + '\n')
}
const waiting = [
  ...new Set(posts.flatMap((d) => [d.x.slug, d.reddit?.slug]).filter((s) => s && !ready(s)))
]
console.log(
  `CHECKLIST.md: X ${xReady}/${dated.length}, r/MemryNote ${rReady}/${reddit.length} hazır; kit -> ${KIT}`
)
console.log(
  waiting.length ? `bekliyor (${waiting.length}): ${waiting.join(', ')}` : 'all media present'
)
