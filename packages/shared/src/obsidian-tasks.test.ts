describe('dataview inline field syntax', () => {
  it.each(['[due::2021-06-20]', '[due:: 2021-06-20]', '[ due::2021-06-20 ]', '(due:: 2021-06-20)'])(
    'tolerates whitespace and brackets in %s',
    (input) => {
      expect(parseObsidianTaskFields(input)).toEqual(fields({ dueDate: '2021-06-20' }))
    }
  )

  it('is case sensitive', () => {
    expect(parseObsidianTaskFields('[dependson:: F12345]')).toEqual(
      fields({ description: '[dependson:: F12345]' })
    )
  })

  it('parses a dataview id and dependsOn', () => {
    expect(parseObsidianTaskFields('Wobble  [id:: abc123]')).toEqual(
      fields({ description: 'Wobble', id: 'abc123' })
    )
    expect(parseObsidianTaskFields('Wobble  [dependsOn:: abc123,def456]')).toEqual(
      fields({ description: 'Wobble', dependsOn: ['abc123', 'def456'] })
    )
  })
})

describe('dependsOn', () => {
  it('drops the spaces around each id', () => {
    expect(parseObsidianTaskFields('⛔ ab , CD ,  EF  ,    GK')).toEqual(
      fields({ dependsOn: ['ab', 'CD', 'EF', 'GK'] })
    )
  })
})

describe('recurrence', () => {
  it.each([
    ['every day', { frequency: 'daily', interval: 1, fromCompletion: false }],
    ['every 3 days', { frequency: 'daily', interval: 3, fromCompletion: false }],
    ['every week', { frequency: 'weekly', interval: 1, fromCompletion: false }],
    ['every 2 weeks', { frequency: 'weekly', interval: 2, fromCompletion: false }],
    ['every month', { frequency: 'monthly', interval: 1, fromCompletion: false }],
    ['every 6 months', { frequency: 'monthly', interval: 6, fromCompletion: false }],
    ['every year', { frequency: 'yearly', interval: 1, fromCompletion: false }],
    ['every 2 years', { frequency: 'yearly', interval: 2, fromCompletion: false }],
    ['every week when done', { frequency: 'weekly', interval: 1, fromCompletion: true }],
    [
      'every weekday',
      { frequency: 'weekly', interval: 1, daysOfWeek: [1, 2, 3, 4, 5], fromCompletion: false }
    ],
    ['every Monday', { frequency: 'weekly', interval: 1, daysOfWeek: [1], fromCompletion: false }],
    [
      'every Monday, Wednesday',
      { frequency: 'weekly', interval: 1, daysOfWeek: [1, 3], fromCompletion: false }
    ],
    [
      'every Tuesday and Thursday',
      { frequency: 'weekly', interval: 1, daysOfWeek: [2, 4], fromCompletion: false }
    ],
    [
      'every Sun, Sat',
      { frequency: 'weekly', interval: 1, daysOfWeek: [0, 6], fromCompletion: false }
    ],
    [
      'every friday when done',
      { frequency: 'weekly', interval: 1, daysOfWeek: [5], fromCompletion: true }
    ]
  ] as const)('maps %s', (text, recurrence) => {
    const parsed = parseObsidianTaskFields(`Wobble 🔁 ${text}`)
    expect(parsed.recurrenceText).toBe(text)
    expect(parsed.recurrence).toEqual(recurrence)
    expect(parsed.description).toBe('Wobble')
  })

  it('keeps the raw text but gives up on an unsupported rule', () => {
    const parsed = parseObsidianTaskFields('Wobble 🔁 every 3rd Thursday')
    expect(parsed.recurrenceText).toBe('every 3rd Thursday')
    expect(parsed.recurrence).toBeNull()
  })

  it('reads the dataview spelling too', () => {
    const parsed = parseObsidianTaskFields('Wobble  [repeat:: every week when done]')
    expect(parsed.recurrenceText).toBe('every week when done')
    expect(parsed.recurrence).toEqual({
      frequency: 'weekly',
      interval: 1,
      fromCompletion: true
    })
  })
})

describe('tags', () => {
  it('preserves casing and dedupes case-insensitively, keeping the first casing', () => {
    const parsed = parseObsidianTaskFields('#Work note #work #WORK #Home')
    expect(parsed.tags).toEqual(['#Work', '#Home'])
  })

  it('collects tags that were peeled from the end', () => {
    const parsed = parseObsidianTaskFields('Wobble #alpha 📅 2026-01-01 #beta')
    expect(parsed.description).toBe('Wobble #alpha #beta')
    expect(parsed.tags).toEqual(['#alpha', '#beta'])
    expect(parsed.dueDate).toBe('2026-01-01')
  })
})

describe('parseObsidianTaskLine', () => {
  it.each(['', 'Just a paragraph', '- a bare list item', '  not a task at all', '[ ] no marker'])(
    'returns null for %s',
    (line) => {
      expect(parseObsidianTaskLine(line)).toBeNull()
    }
  )

  it('parses an indented task', () => {
    expect(parseObsidianTaskLine('    - [ ] Buy milk 📅 2026-01-01')).toEqual(
      taskLine('Buy milk', { indentation: '    ', dueDate: '2026-01-01' })
    )
  })

  it('parses a blockquoted task', () => {
    expect(parseObsidianTaskLine('> - [x] Buy milk')).toEqual(
      taskLine('Buy milk', { indentation: '> ', statusChar: 'x', statusType: 'DONE' })
    )
  })

  it('parses a numbered list task', () => {
    expect(parseObsidianTaskLine('1. [ ] Buy milk')).toEqual(
      taskLine('Buy milk', { listMarker: '1.' })
    )
  })
})

describe('obsidianTaskImportBlocker', () => {
  it.each([
    ['Buy milk ^abc123', 'block-link'],
    ['Buy milk 🆔 dcf64c', 'task-id'],
    ['Buy milk  [id:: dcf64c]', 'task-id'],
    ['Buy milk ⛔ dcf64c', 'depends-on'],
    ['Buy milk  [dependsOn:: dcf64c]', 'depends-on'],
    ['Buy milk 🆔 dcf64c ^abc123', 'block-link'],
    ['Buy milk ⛔ dcf64c 🆔 abc', 'task-id']
  ] as const)('reports %s as %s', (text, blocker) => {
    expect(obsidianTaskImportBlocker(text)).toBe(blocker)
  })

  it.each(['Buy milk', 'Buy milk 📅 2026-01-01 ⏫', 'Buy milk #errand'])('clears %s', (text) => {
    expect(obsidianTaskImportBlocker(text)).toBeNull()
  })
})

describe('vaults that do not use the plugin', () => {
  it('recognises nothing in a plain line', () => {
    expect(hasObsidianTaskFields('Buy milk')).toBe(false)
    expect(parseObsidianTaskFields('Buy milk')).toEqual(fields({ description: 'Buy milk' }))
  })

  it('leaves a plain line untouched through the whole-line parser', () => {
    expect(parseObsidianTaskLine('- [ ] Buy milk')).toEqual(taskLine('Buy milk'))
  })

  it.each([
    'Buy milk 📅 2026-01-01',
    'Buy milk  [due:: 2026-01-01]',
    'Buy milk #errand',
    'Buy milk ^abc123'
  ])('recognises %s', (text) => {
    expect(hasObsidianTaskFields(text)).toBe(true)
  })
})
