// Variant Selector 16 is invisible in an editor, so any test that depends on
// its presence asserts on this first: an editor or a lint autofix that strips
// the character has to fail loudly instead of silently weakening the test.
function hasVariantSelector16(text: string): boolean {
  return /\uFE0F/u.test(text)
}

const EMPTY_FIELDS: ObsidianTaskFields = {
  description: '',
  tags: [],
  priority: null,
  dueDate: null,
  scheduledDate: null,
  startDate: null,
  createdDate: null,
  doneDate: null,
  cancelledDate: null,
  recurrenceText: null,
  recurrence: null,
  onCompletion: null,
  id: null,
  dependsOn: [],
  blockLink: null
}

function fields(overrides: Partial<ObsidianTaskFields> = {}): ObsidianTaskFields {
  return { ...EMPTY_FIELDS, ...overrides }
}

function taskLine(
  description: string,
  overrides: Partial<ObsidianTaskLine> = {}
): ObsidianTaskLine {
  return {
    ...EMPTY_FIELDS,
    description,
    indentation: '',
    listMarker: '-',
    statusChar: ' ',
    statusType: 'TODO',
    ...overrides
  }
}

function readFixture(name: string): string[] {
  const raw = readFileSync(
    new URL(`./obsidian-tasks-fixtures/${name}.approved.md`, import.meta.url),
    'utf8'
  )
  return raw
    .split('\n')
    .map((line) => line.replace(/\r$/, ''))
    .filter((line) => line.trim().length > 0 && !line.trimStart().startsWith('<!--'))
}

// Every fixture line begins with the plugin's own `#task` global filter tag.
function taskTagged(
  description: string,
  overrides: Partial<ObsidianTaskLine> = {}
): ObsidianTaskLine {
  return taskLine(description, { tags: ['#task'], ...overrides })
}

