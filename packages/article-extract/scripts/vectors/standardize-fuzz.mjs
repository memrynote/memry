export function standardizeFuzzVectors(count) {
  const random = rng(0x2c3543)
  return Array.from({ length: count }, () => {
    const length = 2 + Math.floor(random() * 30)
    let soup = ''
    for (let i = 0; i < length; i += 1) soup += PIECES[Math.floor(random() * PIECES.length)]
    const html = page(prose(1) + soup + prose(1))
    return { html, ...standardizeVector(html, standardizeUrl, 'direct') }
  })
}
