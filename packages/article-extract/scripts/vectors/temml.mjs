export function temmlFuzzVectors(count, seed = 0x3543c4) {
  const random = rng(seed)
  return Array.from({ length: count }, () => {
    const length = 1 + Math.floor(random() * 14)
    let soup = ''
    for (let i = 0; i < length; i++) soup += VOCAB[Math.floor(random() * VOCAB.length)]
    return temmlVector([soup, random() < 0.25])
  })
}
