// Vectors for `temml.renderToString(latex, { displayMode, throwOnError: false })` (temml 0.13.3,
// the version Defuddle's math.full.js requires), the call Defuddle makes. Each expected value is
// the markup temml returns. When temml throws, or renders its `<span class="temml-error">` (the
// LaTeX and the message), the vector says `error`: Defuddle reads the `<math>` element of the
// result and keeps the LaTeX as text in both cases, and the port does not reproduce the message.
import { createRequire } from 'node:module'
import { join } from 'node:path'
import { rng } from './dom.mjs'
import { dist } from './probes.mjs'

const require = createRequire(join(dist, 'x.js'))
const temml = require('temml')

export function temmlVector([raw, display]) {
  const input = raw.toWellFormed()
  try {
    const markup = temml.renderToString(input, { displayMode: display, throwOnError: false })
    if (markup.startsWith('<span class="temml-error"')) return { input, display, error: true }
    return { input, display, ok: markup.toWellFormed() }
  } catch {
    return { input, display, error: true }
  }
}

