// Writes apps/ios/Memry/Resources/article-extract.js: the same Defuddle
// extraction desktop's article job runs (@memry/article-extract), bundled for
// the iOS app's JavaScriptCore context.
//
//   node scripts/generate-ios-article-extract.mjs
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const pkg = path.join(root, 'packages/article-extract')
const require = createRequire(path.join(pkg, 'package.json'))
const esbuild = require('esbuild')

const out = path.join(root, 'apps/ios/Memry/Resources/article-extract.js')
await esbuild.build({
  entryPoints: [path.join(pkg, 'src/ios.ts')],
  absWorkingDir: pkg,
  bundle: true,
  format: 'iife',
  platform: 'neutral',
  mainFields: ['module', 'main'],
  conditions: ['import', 'default'],
  target: 'es2020',
  minify: true,
  legalComments: 'none',
  banner: { js: '// Generated by scripts/generate-ios-article-extract.mjs. Do not edit.' },
  outfile: out,
  logLevel: 'warning'
})
console.log(`wrote ${out}`)
