//! The sandbox marker: `<userData>/sandbox-vault.json` holding `{"appVersion":"<v>"}`,
//! the app version that generated `<userData>/Sandbox` (Electron:
//! `apps/desktop/src/main/vault/sandbox.ts`). It is written last, so a crash
//! mid-generation leaves no marker and the next open regenerates.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use crate::vault::fs_atomic::{WriteError, atomic_write};

/// The sandbox folder's name, which is also the vault's display name.
pub const SANDBOX_FOLDER: &str = "Sandbox";
/// The marker file, beside the folder in the app data directory.
pub const MARKER_FILE: &str = "sandbox-vault.json";

pub fn sandbox_path(user_data: &Path) -> PathBuf {
    user_data.join(SANDBOX_FOLDER)
}

pub fn marker_path(user_data: &Path) -> PathBuf {
    user_data.join(MARKER_FILE)
}

/// The app version that generated the folder on disk; `None` when never generated.
/// An unreadable or malformed marker reads as never generated, as in Electron.
pub fn generated_version(user_data: &Path) -> Option<String> {
    let path = marker_path(user_data);
    let bytes = match fs::read(&path) {
        Ok(bytes) => bytes,
        Err(err) if err.kind() == io::ErrorKind::NotFound => return None,
        Err(err) => {
            tracing::warn!(path = %path.display(), error = %err, "sandbox marker unreadable; regenerating");
            return None;
        }
    };
    let version = serde_json::from_slice::<serde_json::Value>(&bytes)
        .ok()
        .and_then(|value| value.get("appVersion")?.as_str().map(str::to_owned));
    if version.is_none() {
        tracing::warn!(path = %path.display(), "sandbox marker malformed; regenerating");
    }
    version
}

/// True when the folder is missing, was generated by another app version, or `reset` asks for a new one.
pub fn needs_generation(user_data: &Path, app_version: &str, reset: bool) -> bool {
    reset
        || generated_version(user_data).as_deref() != Some(app_version)
        || !sandbox_path(user_data).is_dir()
}

/// Records that `app_version` generated the folder. Callers write it after the folder is in place.
pub fn write(user_data: &Path, app_version: &str) -> Result<(), WriteError> {
    // Electron writes JSON.stringify({ appVersion }); serde_json produces the same bytes.
    let bytes = serde_json::json!({ "appVersion": app_version }).to_string();
    atomic_write(&marker_path(user_data), bytes.as_bytes())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn missing_marker_needs_generation() {
        let dir = tempfile::tempdir().unwrap();
        fs::create_dir(sandbox_path(dir.path())).unwrap();
        assert_eq!(generated_version(dir.path()), None);
        assert!(needs_generation(dir.path(), "1.0.0", false));
    }

    #[test]
    fn marker_round_trips_with_electron_bytes() {
        let dir = tempfile::tempdir().unwrap();
        fs::create_dir(sandbox_path(dir.path())).unwrap();
        write(dir.path(), "1.4.2").unwrap();
        assert_eq!(
            fs::read_to_string(marker_path(dir.path())).unwrap(),
            r#"{"appVersion":"1.4.2"}"#
        );
        assert_eq!(generated_version(dir.path()).as_deref(), Some("1.4.2"));
        assert!(!needs_generation(dir.path(), "1.4.2", false));
        assert!(needs_generation(dir.path(), "1.4.2", true));
        assert!(needs_generation(dir.path(), "1.5.0", false));
    }

    #[test]
    fn marker_without_folder_needs_generation() {
        let dir = tempfile::tempdir().unwrap();
        write(dir.path(), "1.4.2").unwrap();
        assert!(needs_generation(dir.path(), "1.4.2", false));
    }

    #[test]
    fn malformed_marker_reads_as_never_generated() {
        let dir = tempfile::tempdir().unwrap();
        fs::create_dir(sandbox_path(dir.path())).unwrap();
        for bytes in [&b"not json"[..], br#"{"appVersion":7}"#, b"null"] {
            fs::write(marker_path(dir.path()), bytes).unwrap();
            assert_eq!(generated_version(dir.path()), None);
            assert!(needs_generation(dir.path(), "1.4.2", false));
        }
    }
}
