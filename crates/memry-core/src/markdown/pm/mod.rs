//! A ProseMirror document model in Rust: the slice of `prosemirror-model` 1.25
//! the markdown converter needs, with the memry schema as data.
//!
//! The converter's TypeScript path builds a ProseMirror document from HTML
//! (`DOMParser`), reads and writes the Yjs fragment through y-prosemirror, and
//! turns nodes into BlockNote blocks. Every one of those steps decides by what
//! the schema accepts, so the schema lives here once: [`schema::Schema`] holds
//! node and mark types, [`content::ContentMatch`] is the compiled content
//! expression (`fillBefore`, `findWrapping`), and [`model`] holds `Node`,
//! `Fragment` and `Mark` with the checked constructors `schema.node` and
//! `schema.text` expose.
//!
//! Proof: the `pm-schema` and `yxml` files of the `markdown-convert` vector
//! class, generated by running the TypeScript schema and y-prosemirror in place.

pub mod content;
pub mod model;
pub mod ops;
pub mod schema;
pub mod specs;

pub use content::ContentMatch;
pub use model::{Attrs, Fragment, Mark, Node, PmError};
pub use schema::{MarkTypeId, NodeTypeId, Schema};
