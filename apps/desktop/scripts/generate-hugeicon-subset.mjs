#!/usr/bin/env node
/**
 * Regenerates `src/renderer/src/lib/icons/hugeicons-subset.ts`.
 *
 * The subset re-exports each eagerly used glyph from its own module file so the
 * renderer entry never statically reaches `@hugeicons/core-free-icons`. That
 * barrel is also imported dynamically to resolve user-picked icon keys by name,
 * and rollup refuses to split a module that is reached both ways, so the whole
 * 5,094-icon export surface would otherwise land in the entry chunk.
 *
 *   node scripts/generate-hugeicon-subset.mjs           # write
 *   node scripts/generate-hugeicon-subset.mjs --check    # fail if stale
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const rendererRoot = join(appRoot, 'src/renderer/src')
const outputPath = join(rendererRoot, 'lib/icons/hugeicons-subset.ts')
const packageRoot = join(appRoot, 'node_modules/@hugeicons/core-free-icons')

const SUBSET_SPECIFIERS = new Set([
  '@/lib/icons/hugeicons-subset',
  './hugeicons-subset',
  './icons/hugeicons-subset',
  '../icons/hugeicons-subset'
])

function sourceFiles(dir) {
  const found = []
  for (const entry of readdirSync(dir)) {
    if (entry === 'node_modules') continue
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) {
      found.push(...sourceFiles(full))
    } else if (/\.tsx?$/.test(entry) && full !== outputPath) {
      found.push(full)
    }
  }
  return found
}

function importedNames() {
  const names = new Set()
  const pattern = /import\s+\{([^}]*)\}\s+from\s+'([^']+)'/g
  for (const file of sourceFiles(rendererRoot)) {
    const text = readFileSync(file, 'utf8')
    for (const [, clause, specifier] of text.matchAll(pattern)) {
      if (!SUBSET_SPECIFIERS.has(specifier)) continue
      const bare = clause.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '')
      for (const part of bare.split(',')) {
        const name = part
          .trim()
          .split(/\s+as\s+/)[0]
          .trim()
        if (name) names.add(name)
      }
    }
  }
  return [...names].sort()
}

function render(names) {
  const missing = names.filter((name) => !existsSync(join(packageRoot, `dist/esm/${name}.js`)))
  if (missing.length > 0) {
    throw new Error(`@hugeicons/core-free-icons has no module for: ${missing.join(', ')}`)
  }
  const lines = names.map(
    (name) => `export { default as ${name} } from '@hugeicons/core-free-icons/${name}'`
  )
  return [
    '// Generated by scripts/generate-hugeicon-subset.mjs. Do not edit by hand.',
    '',
    ...lines,
    ''
  ].join('\n')
}

const names = importedNames()
if (names.length === 0) {
  throw new Error(`no imports from the subset module found under ${rendererRoot}`)
}
const next = render(names)

if (process.argv.includes('--check')) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : ''
  if (current !== next) {
    console.error(
      'hugeicons-subset.ts is out of date. Run: node scripts/generate-hugeicon-subset.mjs'
    )
    process.exit(1)
  }
  console.log(`hugeicons-subset.ts is up to date (${names.length} icons).`)
} else {
  writeFileSync(outputPath, next)
  console.log(`Wrote ${outputPath} (${names.length} icons).`)
}
