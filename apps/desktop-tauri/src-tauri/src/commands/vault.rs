/// Next to the current vault when one is registered, else `<documents>/Memry`.
#[tauri::command]
#[specta::specta]
pub async fn vault_get_default_parent(app: AppHandle<Wry>) -> Result<String, CommandError> {
    let session = session(&app);
    let documents = app.path().document_dir().map_err(|error| {
        CommandError::new(ErrorKind::Internal, "documents_dir", error.to_string())
    })?;
    blocking("vault_get_default_parent", move || {
        let parent = session
            .registry()
            .current()
            .and_then(|current| PathBuf::from(current).parent().map(PathBuf::from))
            .unwrap_or_else(|| documents.join("Memry"));
        Ok(parent.to_string_lossy().into_owned())
    })
    .await
}

/// Opens `path` through `open`, offering repair once when its database is damaged.
fn open_offering_repair(
    app: &AppHandle<Wry>,
    path: &std::path::Path,
    open: impl Fn(
        &Session,
    )
        -> Result<memry_desktop::session::VaultOpened, memry_desktop::session::SessionError>,
) -> SelectVaultResponse {
    let session = session(app);
    let prompt = &app.state::<RepairPrompt>().0;
    open_response(prompt.open_with_offer(&session, &asker(app), path, || open(&session)))
}

#[tauri::command]
#[specta::specta]
pub async fn vault_select(
    app: AppHandle<Wry>,
    path: Option<String>,
) -> Result<SelectVaultResponse, CommandError> {
    blocking("vault_select", move || {
        let picked = match path {
            Some(path) => PathBuf::from(path),
            None => match dialogs::pick_folder(&app, &picker_title(&app), None) {
                Some(folder) => folder,
                None => return Ok(SelectVaultResponse::no_folder()),
            },
        };
        // The picker, the Obsidian prompt and its copy run before the session's lifecycle
        // queue, as in Electron: a dialog left open must not hold up a close or a quit.
        let folder = match resolve_obsidian_open(&picked, |source, target| {
            ask_obsidian(&app, source, target)
        }) {
            Ok(decision) => match decision.into_folder() {
                Some(folder) => folder,
                None => return Ok(SelectVaultResponse::no_folder()),
            },
            Err(error) => {
                tracing::error!(
                    kind = ?error.kind(),
                    "vault_select: the Obsidian vault copy failed"
                );
                return Ok(SelectVaultResponse::failure(format!(
                    "Could not copy the Obsidian vault: {error}"
                )));
            }
        };
        Ok(open_offering_repair(&app, &folder, |session| {
            session.replace(&folder, OpenSource::Select)
        }))
    })
    .await
}

#[tauri::command]
#[specta::specta]
pub async fn vault_create(
    app: AppHandle<Wry>,
    parent_path: String,
    name: String,
) -> Result<SelectVaultResponse, CommandError> {
    let session = session(&app);
    blocking("vault_create", move || {
        Ok(create_response(
            session.create(&PathBuf::from(parent_path), &name),
        ))
    })
    .await
}

#[tauri::command]
#[specta::specta]
pub async fn vault_switch(
    app: AppHandle<Wry>,
    path: String,
) -> Result<SelectVaultResponse, CommandError> {
    blocking("vault_switch", move || {
        let target = PathBuf::from(path);
        Ok(open_offering_repair(&app, &target, |session| {
            session.switch(&target)
        }))
    })
    .await
}

