#[tauri::command]
#[specta::specta]
pub async fn vault_reveal(app: AppHandle<Wry>, path: String) -> Result<(), CommandError> {
    #[cfg(feature = "e2e")]
    if crate::e2e::record_reveal(&app, &path) {
        return Ok(());
    }
    app.opener().reveal_item_in_dir(&path).map_err(|error| {
        let error = CommandError::new(ErrorKind::Internal, "reveal_failed", error.to_string());
        log_failure("vault_reveal", &error);
        error
    })
}

#[tauri::command]
#[specta::specta]
pub async fn vault_set_icon(
    app: AppHandle<Wry>,
    path: String,
    icon: Option<String>,
) -> Result<(), CommandError> {
    let session = session(&app);
    blocking("vault_set_icon", move || {
        let now_ms = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map_or(0, |elapsed| {
                i64::try_from(elapsed.as_millis()).unwrap_or(i64::MAX)
            });
        session
            .set_icon(&path, icon.as_deref(), now_ms)
            .map_err(icon_error)
    })
    .await
}

fn icon_error(error: IconError) -> CommandError {
    let (kind, code) = match &error {
        IconError::Invalid => (ErrorKind::Invalid, "invalid_icon"),
        IconError::NotRegistered(_) => (ErrorKind::NotFound, "vault_not_registered"),
        IconError::Unreachable(_) => (ErrorKind::NotFound, "vault_unreachable"),
        IconError::Registry(_) | IconError::Unreadable { .. } | IconError::Write { .. } => {
            (ErrorKind::Storage, "vault_icon_failed")
        }
    };
    CommandError::new(kind, code, error.to_string())
}
