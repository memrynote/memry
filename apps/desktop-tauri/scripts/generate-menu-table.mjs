#!/usr/bin/env node
/**
 * Regenerates `crates/memry-desktop/src/shell/menu_table.generated.rs`: the commands the native
 * menu lists (`menu: true`) or shows an accelerator for (`keyboard.menuAccelerator`), with that
 * default binding, read from `packages/contracts/src/commands`.
 *
 *   tsx scripts/generate-menu-table.mjs           # write
 *   tsx scripts/generate-menu-table.mjs --check   # fail if stale
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { COMMANDS } from '@memry/contracts/commands'

const outputPath = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../../../crates/memry-desktop/src/shell/menu_table.generated.rs'
)

const str = (value) => JSON.stringify(value)

function binding(b) {
  const m = b.modifiers
  return `BindingRow { key: ${str(b.key)}, meta: ${!!m.meta}, ctrl: ${!!m.ctrl}, shift: ${!!m.shift}, alt: ${!!m.alt} }`
}

function defaultOf(spec) {
  const d = spec.default
  const pair = 'mac' in d ? d : { mac: d, other: d }
  return `Some(DefaultBinding { mac: ${binding(pair.mac)}, other: ${binding(pair.other)} })`
}

export function render() {
  const rows = Object.entries(COMMANDS)
    .map(([id, meta]) => {
      const accelerates = meta.keyboard?.owner === 'app' && meta.keyboard.menuAccelerator === true
      return [id, meta, accelerates]
    })
    .filter(([, meta, accelerates]) => meta.menu === true || accelerates)
    .map(([id, meta, accelerates]) => {
      const accelerator = accelerates ? defaultOf(meta.keyboard) : 'None'
      return `    MenuCommandRow { id: ${str(id)}, group: ${str(meta.group)}, menu: ${meta.menu === true}, accelerator: ${accelerator} },`
    })
  return `// @generated by apps/desktop-tauri/scripts/generate-menu-table.mjs from
// packages/contracts/src/commands. Do not edit; run \`pnpm ipc:generate\`.

use super::menu_table::{BindingRow, DefaultBinding, MenuCommandRow};

#[rustfmt::skip]
pub const MENU_COMMANDS: &[MenuCommandRow] = &[
${rows.join('\n')}
];
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = render()
  if (process.argv.includes('--check')) {
    let current = ''
    try {
      current = readFileSync(outputPath, 'utf8')
    } catch {
      // A missing file is stale.
    }
    if (current !== next) {
      console.error('menu_table.generated.rs is stale; run `pnpm ipc:generate`')
      process.exit(1)
    }
  } else {
    writeFileSync(outputPath, next)
  }
}
