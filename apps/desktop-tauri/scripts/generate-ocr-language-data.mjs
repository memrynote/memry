#!/usr/bin/env node
/**
 * Regenerates `crates/memry-desktop/src/services/ocr_languages/data.generated.rs`: the OCR
 * languages, the one each UI locale reads in (`OCR_LANGUAGE_BY_LOCALE` of
 * `@memry/contracts/ocr-languages-api`) and the size and sha256 each downloaded language is
 * pinned to (`OCR_LANGUAGE_DATA` of Electron's `src/main/file-text/ocr-language-data.ts`). The
 * pins are the bytes the sync server serves, so a pack Electron downloaded passes here too.
 *
 *   tsx scripts/generate-ocr-language-data.mjs           # write
 *   tsx scripts/generate-ocr-language-data.mjs --check   # fail if stale
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { BUNDLED_OCR_LANGUAGE, OCR_LANGUAGE_BY_LOCALE } from '@memry/contracts/ocr-languages-api'
// apps/desktop is a CommonJS package, whose named exports an ESM import cannot see.
const { OCR_LANGUAGE_DATA } = createRequire(import.meta.url)(
  '../../desktop/src/main/file-text/ocr-language-data.ts'
)

const outputPath = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../../../crates/memry-desktop/src/services/ocr_languages/data.generated.rs'
)

const str = (value) => JSON.stringify(value)
const variant = (code) =>
  code
    .split('_')
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('')

export function render() {
  const codes = [...new Set(Object.values(OCR_LANGUAGE_BY_LOCALE))].toSorted()
  const missing = codes.filter((code) => code !== BUNDLED_OCR_LANGUAGE && !OCR_LANGUAGE_DATA[code])
  if (missing.length > 0) throw new Error(`no pin for ${missing.join(', ')}`)

  const variants = codes.map((code) => `    #[serde(rename = ${str(code)})]\n    ${variant(code)},`)
  const all = codes.map((code) => `        Self::${variant(code)},`)
  const names = codes.map((code) => `            Self::${variant(code)} => ${str(code)},`)
  const locales = Object.entries(OCR_LANGUAGE_BY_LOCALE).map(
    ([locale, code]) => `        ${str(locale)} => Some(Self::${variant(code)}),`
  )
  const pins = codes
    .filter((code) => code !== BUNDLED_OCR_LANGUAGE)
    .map((code) => {
      const { bytes, sha256 } = OCR_LANGUAGE_DATA[code]
      return `    (OcrLanguage::${variant(code)}, Pin { bytes: ${bytes}, sha256: ${str(sha256)} }),`
    })

  return `// @generated by apps/desktop-tauri/scripts/generate-ocr-language-data.mjs from
// packages/contracts/src/ocr-languages-api.ts and
// apps/desktop/src/main/file-text/ocr-language-data.ts. Do not edit; run \`pnpm ipc:generate\`.

use serde::{Deserialize, Serialize};

use super::Pin;

/// A Tesseract language code, one per UI locale.
#[rustfmt::skip]
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize, specta::Type)]
pub enum OcrLanguage {
${variants.join('\n')}
}

#[rustfmt::skip]
impl OcrLanguage {
    pub const ALL: [Self; ${codes.length}] = [
${all.join('\n')}
    ];

    /// Ships inside the app and is always read. Every other language is downloaded.
    pub const BUNDLED: Self = Self::${variant(BUNDLED_OCR_LANGUAGE)};

    pub fn code(self) -> &'static str {
        match self {
${names.join('\n')}
        }
    }

    /// The language a UI locale reads in.
    pub fn for_locale(locale: &str) -> Option<Self> {
        match locale {
${locales.join('\n')}
            _ => None,
        }
    }
}

/// The data the sync server serves at \`/ocr/v1/<lang>.traineddata.gz\`, pinned to its exact bytes.
#[rustfmt::skip]
pub const PINS: &[(OcrLanguage, Pin)] = &[
${pins.join('\n')}
];
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = render()
  if (process.argv.includes('--check')) {
    let current = ''
    try {
      current = readFileSync(outputPath, 'utf8')
    } catch {
      // A missing file is stale.
    }
    if (current !== next) {
      console.error('data.generated.rs is stale; run `pnpm ipc:generate`')
      process.exit(1)
    }
  } else {
    writeFileSync(outputPath, next)
  }
}
